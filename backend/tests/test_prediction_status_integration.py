    # TEST 7 — BOUNDARY BEHAVIOR & RAW PREDICTION BEFORE DISPLAY ROUNDING
    # ==================================================================

    def test_07_exact_boundaries_and_raw_prediction_before_rounding(self):
        """
        Verify exact boundary cases and guarantee that raw score BEFORE display
        rounding governs status classification:
        - 60.0 -> NORMAL
        - 59.999 -> MONITOR (even though rounded display is 60.00)
        - 50.0 -> MONITOR
        - 49.999 -> INTERVENTION (even though rounded display is 50.00)
        """
        self._setup_semester_1_student(student_id=1)

        boundary_test_cases = [
            (60.0, 60.0, "NORMAL"),
            (59.999, 60.0, "MONITOR"),
            (50.0, 50.0, "MONITOR"),
            (49.999, 50.0, "INTERVENTION"),
        ]

        for raw_val, expected_display, expected_status in boundary_test_cases:
            with self.subTest(raw_val=raw_val, expected_display=expected_display, expected_status=expected_status):
                with patch("app.routers.predictions.predict_final_score", return_value=raw_val):
                    status_code, body = self._post("/predictions/students/1", {"semester": 1})

                self.assertEqual(status_code, 200)
                self.assertEqual(body["predicted_final_semester_score"], expected_display)
                self.assertEqual(
                    body["academic_status"],
                    expected_status,
                    f"Raw prediction {raw_val} must result in status {expected_status}, not distorted by display rounding {expected_display}.",
                )

