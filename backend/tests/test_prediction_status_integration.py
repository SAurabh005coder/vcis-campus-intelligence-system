    def test_12_existing_error_behavior_remains_unchanged(self):
        """
        Verify existing error handling remains intact:
        - Non-existent student -> 404
        - Insufficient data -> 422
        - Invalid student ID (<= 0) -> 400
        - Invalid semester (< 1 or > 4) -> 422
        """
        # 1. Non-existent student -> 404
        status_code, body = self._post("/predictions/students/9999", {"semester": 1})
        self.assertEqual(status_code, 404)
        self.assertIn("detail", body)

        # 2. Insufficient data -> 422
        self._create_student(student_id=5, current_semester=1)
        status_code, body = self._post("/predictions/students/5", {"semester": 1})
        self.assertEqual(status_code, 422)
        self.assertIn("detail", body)

        # 3. Invalid student ID <= 0 -> 400
        status_code, body = self._post("/predictions/students/0", {"semester": 1})
        self.assertEqual(status_code, 400)
        self.assertEqual(body["detail"], "Invalid student ID.")

        # 4. Invalid semester -> 422 (Out of program duration or <= 0)
        status_code, body = self._post("/predictions/students/5", {"semester": 5})
        self.assertEqual(status_code, 422)

        status_code, body = self._post("/predictions/students/5", {"semester": 0})
        self.assertEqual(status_code, 422)


