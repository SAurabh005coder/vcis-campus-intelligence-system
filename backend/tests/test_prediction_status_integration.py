    def test_11_ct2_and_final_do_not_affect_prediction_or_status(self):
        """
        Verify that adding CT2 and FINAL assessment records in the current semester
        does NOT alter features, prediction value, or the resulting academic_status.
        """
        self._setup_semester_1_student(student_id=1)
        status_code_before, body_before = self._post("/predictions/students/1", {"semester": 1})
        self.assertEqual(status_code_before, 200)

        # Add CT2 and FINAL to enrollment 1
        self._create_assessment(
            assessment_id=991,
            enrollment_id=1,
            assessment_type=AssessmentType.CT2,
            assessment_name="Class Test 2 Leak Test",
            max_marks=100,
            obtained_marks=10,
        )
        self._create_assessment(
            assessment_id=992,
            enrollment_id=1,
            assessment_type=AssessmentType.FINAL,
            assessment_name="Current Semester Final Leak Test",
            max_marks=100,
            obtained_marks=5,
        )

        status_code_after, body_after = self._post("/predictions/students/1", {"semester": 1})
        self.assertEqual(status_code_after, 200)

        # Feature dictionary, prediction, and academic status must be strictly identical
        self.assertEqual(body_before["features"], body_after["features"])
        self.assertEqual(body_before["predicted_final_semester_score"], body_after["predicted_final_semester_score"])
        self.assertEqual(body_before["academic_status"], body_after["academic_status"])

    # ==================================================================
    # TEST 12 — EXISTING ERROR BEHAVIOR REMAINS UNCHANGED
